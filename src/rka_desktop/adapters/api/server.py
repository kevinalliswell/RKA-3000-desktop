"""Authenticated loopback JSON API used by the Tauri shell (and the Vite dev proxy).

Security model: bind 127.0.0.1 only, dynamic port reported on stdout as one JSON line, every
request must carry ``Authorization: Bearer <token>`` where the token is generated by the
desktop shell per launch and passed through the ``RKA3000_API_TOKEN`` environment variable.
Request bodies are capped at 1 MB and connections time out after 10 s.
"""

