"""Ports (interfaces) the application layer depends on. Implementations are injected by bootstrap."""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
from typing import Any, Protocol

from rka_desktop.domain.entities import DeviceSnapshot, Measurement, MultiDeviceSnapshot
from rka_desktop.domain.recipe import RecipeStep


class RecipeStore(Protocol):
    def list_recipes(self) -> list[dict[str, Any]]: ...
    def get_recipe(self, recipe_id: int) -> dict[str, Any] | None: ...
    def get_recipe_steps(self, recipe_id: int) -> list[dict[str, Any]]: ...
    def create_recipe(self, name: str, steps: list[dict[str, Any]]) -> int: ...
    def update_recipe(self, recipe_id: int, name: str, steps: list[dict[str, Any]]) -> None: ...
    def delete_recipe(self, recipe_id: int) -> None: ...
    def count_experiments_for_recipe(self, recipe_id: int) -> int: ...


class ExperimentStore(Protocol):
    def create_experiment(self, name: str, recipe_id: int | None = None) -> int: ...
    def finish_experiment(self, experiment_id: int, status: str) -> None: ...
    def set_experiment_status(self, experiment_id: int, status: str) -> None: ...
    def set_sample_params(self, experiment_id: int, initial_mass_g: float, tfe_pct: float, feo_pct: float) -> None: ...
    def insert_measurements(self, measurements: list[Measurement]) -> int: ...
    def fetch_measurements(self, experiment_id: int) -> list[dict[str, Any]]: ...
    def fetch_measurements_page(self, experiment_id: int, *, limit: int, offset: int) -> list[dict[str, Any]]: ...
    def count_measurements(self, experiment_id: int) -> int: ...
    def rename_experiment(self, experiment_id: int, name: str) -> None: ...
    def delete_experiment(self, experiment_id: int) -> None: ...
    def get_latest_experiment_id(self) -> int | None: ...
    def list_experiments(self, limit: int = 100) -> list[dict[str, Any]]: ...
    def get_experiment_detail(self, experiment_id: int) -> dict[str, Any] | None: ...
    def get_experiment_summary(self, experiment_id: int) -> dict[str, Any] | None: ...


class AlarmStore(Protocol):
    def create_alarm(self, experiment_id: int | None, code: str, level: str, message: str) -> int: ...
    def acknowledge_latest_alarm(self, experiment_id: int, actor: str = "operator") -> bool: ...
    def list_unacknowledged_alarms(self, experiment_id: int) -> list[dict[str, Any]]: ...
    def list_alarm_history(self, experiment_id: int | None = None, limit: int = 100) -> list[dict[str, Any]]: ...


class AuditStore(Protocol):
    def log_action(self, actor: str, action: str, detail: str = "") -> None: ...
    def list_audit_logs(self, limit: int = 100) -> list[dict[str, Any]]: ...


@dataclass(frozen=True)
class RunControlFeedback:
    command: str | None
    expected_word: int
    feedback_word: int
    is_consistent: bool
    message: str


@dataclass(frozen=True)
class GatewayCapabilities:
    """What the configured device backend can do; the runner refuses modes it cannot honour."""

    temperature_program: bool
    temperature_setpoint: bool
    run_control_word: bool
    alarm_words: bool
    multi_device_status: bool
    balance_tare: bool


class ExperimentGateway(Protocol):
    """Device access used by the experiment runner. One implementation per backend."""

    capabilities: GatewayCapabilities

    def connect(self) -> bool: ...
    def close(self) -> None: ...
    def read_snapshot(self) -> DeviceSnapshot: ...
    def degraded_devices(self) -> tuple[str, ...]: ...
    def apply_gas_setpoints(self, *, n2_lpm: float, h2_lpm: float, co_lpm: float) -> dict[str, float]: ...
    def apply_temperature_setpoint(self, *, temperature_c: float, ramp_rate_cpm: float) -> None: ...
    def download_temperature_program(self, steps: list[RecipeStep]) -> dict[str, Any]: ...
    def issue_run_control(self, command: str) -> int: ...
    def evaluate_run_control_feedback(self, feedback_word: int) -> RunControlFeedback: ...
    # Manual device access (device page); None when the backend has no multi-device view.
    def read_multi_snapshot(self) -> MultiDeviceSnapshot | None: ...
    def set_mfc_flow(self, address: int, lpm: float) -> None: ...
    def set_temperature_sv(self, celsius: float) -> None: ...
    def tare_balance(self) -> bool: ...
    def describe(self) -> dict[str, Any]: ...


class Exporter(Protocol):
    """File writers for experiment data; the application never touches csv/openpyxl directly."""

    def write_measurements_csv(self, rows: list[dict[str, Any]], path: Path) -> Path: ...
    def write_measurements_excel(self, rows: list[dict[str, Any]], path: Path) -> Path: ...
    def write_summary_csv(self, summary: dict[str, Any] | None, path: Path) -> Path: ...


class ReportWriter(Protocol):
    def generate_excel_report(self, experiment: dict[str, Any], result: Any, file_path: Path) -> Path: ...


class Clock(Protocol):
    def now(self) -> datetime: ...
    def monotonic(self) -> float: ...
